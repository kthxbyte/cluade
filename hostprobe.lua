-- hostprobe.lua -- probe the host cluade is running on and build a system prompt
-- that describes it accurately, instead of hardcoding environment claims.
--
-- The point: the old system prompt asserted "OpenWRT / busybox ash / no Python",
-- which is false on most hosts and misdirects the model. Here BASE holds only the
-- claim-free role + communication guidance, and the Environment section is
-- generated from a live probe (OS, arch, /bin/sh flavor, Python availability).
-- A fingerprint of those facts is stored so a later boot can notice host drift.
--
-- _run is the single shell seam, injected in tests so probing is deterministic.

local M = {}

-- Role + communication guidance only. No environment claims live here -- those
-- are generated by environment_section() from a probe, so the prompt never
-- states something false about the host.
M.BASE = [[You are cluade, a minimal coding agent for software engineering tasks.

Communication:
- Be concise. Your output is displayed on a terminal.
- Use GitHub-flavored markdown for formatting.
- Do not add unnecessary explanation unless asked.]]

-- Shell seam: run a command and return its trimmed stdout (stderr discarded).
-- Overridden in tests. Returns "" on any failure.
function M._run(cmd)
  local f = io.popen(cmd .. " 2>/dev/null")
  if not f then return "" end
  local out = f:read("*a") or ""
  f:close()
  return (out:gsub("%s+$", ""))
end

-- Probe the host. Every field has a safe fallback so a missing command never
-- turns into an error: os/arch -> "unknown", shell -> "sh", bash -> false,
-- python -> false (else the interpreter path).
function M.probe()
  local run = M._run
  local os_name = run("uname -s"); if os_name == "" then os_name = "unknown" end
  local arch = run("uname -m"); if arch == "" then arch = "unknown" end

  local sh_target = run("readlink -f /bin/sh")
  local shell = sh_target:match("([^/]+)$")
  if not shell or shell == "" then shell = "sh" end

  local bash = run("command -v bash") ~= ""

  local python = run("command -v python3")
  if python == "" then python = run("command -v python") end
  if python == "" then python = false end

  return { os = os_name, arch = arch, shell = shell, bash = bash, python = python }
end

-- The generated "Environment:" block, describing what the probe found.
function M.environment_section(p)
  local lines = { "Environment:" }
  lines[#lines + 1] = "- OS: " .. p.os .. " (" .. p.arch .. ")."
  local shell_line = "- Shell: /bin/sh is " .. p.shell .. ". Prefer POSIX sh-compatible syntax."
  if p.bash then shell_line = shell_line .. " bash is available." end
  lines[#lines + 1] = shell_line
  if p.shell == "busybox" then
    lines[#lines + 1] = "- Busybox applets provide grep, sed, awk, find, head, tail, cut, sort."
  end
  if p.python then
    lines[#lines + 1] = "- Python: " .. p.python .. " is available."
  else
    lines[#lines + 1] = "- Python is not available; do not use Python."
  end
  lines[#lines + 1] = "- Use /tmp for temporary files."
  return table.concat(lines, "\n")
end

-- The full system prompt: the static base followed by the generated environment.
function M.build_prompt(p)
  return M.BASE .. "\n\n" .. M.environment_section(p)
end

-- The comparable subset used to detect host drift. Python collapses to a boolean
-- (presence is what matters for the prompt, not the exact path).
function M.fingerprint(p)
  return {
    os = p.os,
    arch = p.arch,
    shell = p.shell,
    python = p.python and true or false,
  }
end

-- True if two fingerprints disagree on any field cluade calibrates the prompt to.
function M.differs(a, b)
  if not a or not b then return true end
  return a.os ~= b.os or a.arch ~= b.arch or a.shell ~= b.shell
    or (a.python and true or false) ~= (b.python and true or false)
end

-- Decide what to do with a config given the current host probe. Mutates config
-- (system_prompt + host) only when it generates or regenerates. ask_fn is
-- function(question)->bool, or nil in non-interactive mode (no human to ask).
-- Returns action, message:
--   "generated"   first run / old config with no stored host -> built and stored
--   "ok"          host matches the stored fingerprint -> nothing changed
--   "regenerated" host drifted and the human approved -> rebuilt and stored
--   "drift"       host drifted but declined or non-interactive -> nothing changed
-- message is a short human string for every action except "ok" (nil).
function M.resolve(config, probe, ask_fn)
  local function apply()
    config.system_prompt = M.build_prompt(probe)
    config.host = M.fingerprint(probe)
  end
  local function label(fp) return (fp.os or "?") .. "/" .. (fp.arch or "?") end

  if not config.system_prompt or not config.host then
    apply()
    return "generated", label(config.host)
  end

  local current = M.fingerprint(probe)
  if not M.differs(config.host, current) then
    return "ok", nil
  end

  local transition = label(config.host) .. " -> " .. label(current)
  -- No "[y/N]" here: the caller's yes/no prompt (Agent:prompt_yes_no) appends it.
  if ask_fn and ask_fn("host changed (" .. transition .. "); regenerate system prompt?") then
    apply()
    return "regenerated", transition
  end
  return "drift", transition
end

return M
